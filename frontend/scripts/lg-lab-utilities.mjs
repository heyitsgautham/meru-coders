// Generates src/styles/lg-lab-utilities.css: CSS for the Tailwind utilities the L-G Lab uses,
// scoped to the L-G Lab page.
//
//   npm run css:lg-lab           # write the file
//   npm run css:lg-lab -- --check  # exit 1 if the committed file is out of date
//
// The L-G Lab is styled with Tailwind classes, and most of them have no effect today:
// - index.css is a Tailwind build frozen when the app was exported from Figma, so classes added
//   since then (bg-blue-50, flex-wrap, grid-cols-4, ...) have no CSS at all;
// - the ones it does define sit in @layer utilities, and index.css's own unlayered
//   "* { margin: 0; padding: 0 }" reset beats every layered rule, so mx-auto, px-6, p-4 and the
//   rest of the spacing utilities are dead too.
// Recompiling all of Tailwind restyles most of the app, so this compiles the classes the L-G Lab
// files use, unlayered, with every rule prefixed by :where(.lg-lab-page): no added specificity,
// and no effect on any other page.

import { compile } from 'tailwindcss';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const frontend = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCES = ['src/pages/LGLab.tsx', 'src/components/lg-lab'];
const OUTPUT = path.join(frontend, 'src/styles/lg-lab-utilities.css');
const SCOPE = ':where(.lg-lab-page)';

function sourceFiles() {
  return SOURCES.flatMap((entry) => {
    const full = path.join(frontend, entry);
    if (!fs.statSync(full).isDirectory()) return [full];
    return fs
      .readdirSync(full, { recursive: true })
      .map((name) => path.join(full, name))
      .filter((file) => /\.tsx?$/.test(file) && !/\.test\.tsx?$/.test(file));
  }).sort();
}

// Every token between whitespace, quotes, backticks and braces, as Tailwind's own scanner reads
// source files; it discards the tokens that are not utilities.
function candidates(files) {
  const tokens = new Set();
  for (const file of files) {
    for (const token of fs.readFileSync(file, 'utf8').split(/[\s"'`{}$]+/)) if (token) tokens.add(token);
  }
  return [...tokens].sort();
}

async function compileUtilities(classes) {
  const tailwind = path.join(frontend, 'node_modules/tailwindcss');
  const loadStylesheet = async (id) => {
    const file = path.join(tailwind, id.replace(/^tailwindcss\/?/, '') || 'index.css');
    return { path: file, base: path.dirname(file), content: fs.readFileSync(file, 'utf8') };
  };
  // theme(inline) writes literal values, so the output defines no theme variables of its own.
  const input = '@import "tailwindcss/theme.css" theme(inline);\n@import "tailwindcss/utilities.css";';
  const compiler = await compile(input, { base: frontend, loadStylesheet });
  return compiler.build(classes);
}

// Split the compiled CSS into top-level rules and at-rules, and scope each class rule.
function scopeRules(css) {
  const blocks = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < css.length; i++) {
    if (css[i] === '{') depth++;
    if (css[i] === '}' && --depth === 0) {
      blocks.push(css.slice(start, i + 1).trim());
      start = i + 1;
    }
  }
  const classOf = (selector) => selector.match(/^\.((?:\\.|[\w-])+)/)?.[1];
  const scopeRule = (rule) => {
    const selector = rule.slice(0, rule.indexOf('{')).trim();
    const name = classOf(selector);
    if (!name) return null;
    return `${SCOPE} ${rule}`;
  };
  const out = [];
  for (const block of blocks) {
    if (block.startsWith('/*!')) continue;
    if (block.startsWith('@property')) {
      out.push(block);
      continue;
    }
    if (block.startsWith('@')) {
      const head = block.slice(0, block.indexOf('{') + 1);
      const inner = scopeRules(block.slice(head.length, -1));
      if (inner.trim()) out.push(`${head}\n${inner.replace(/^/gm, '  ')}\n}`);
      continue;
    }
    const scoped = scopeRule(block);
    if (scoped) out.push(scoped);
  }
  return out.join('\n');
}

const HEADER = `/* Generated by scripts/lg-lab-utilities.mjs; do not edit. Run: npm run css:lg-lab
 * The Tailwind utilities the L-G Lab uses. index.css lacks many of them, and its unlayered
 * "* { margin: 0; padding: 0 }" reset overrides the rest. Scoped to .lg-lab-page. */
`;

const files = sourceFiles();
const compiled = await compileUtilities(candidates(files));
const css = `${HEADER}${scopeRules(compiled)}\n`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
  if (current !== css) {
    console.error(`${path.relative(frontend, OUTPUT)} is out of date; run npm run css:lg-lab`);
    process.exit(1);
  }
  console.log(`${path.relative(frontend, OUTPUT)} is up to date`);
} else {
  fs.writeFileSync(OUTPUT, css);
  console.log(`wrote ${path.relative(frontend, OUTPUT)} (${css.split('\n').length} lines from ${files.length} files)`);
}
